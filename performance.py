"""Performance model and LLM output parsing.

The director LLM no longer splits the reply into sentences. Instead it
**inserts inline ``[tag]`` markers** into the original reply text, where
each tag names the emotion/tone for the text that follows it (up to the
next tag). This module parses that tagged text back into a list of
performance segments:

- ``text``: the dialogue of this segment (original text, unmodified).
- ``emotion``: one of the fixed 24-word emotion vocabulary shared with the
  frontend engine; text before the first tag defaults to ``neutral``.
- ``intensity``: no longer generated by the LLM; always the fixed default.
- ``start`` / ``end``: timing inside the single shared TTS audio, filled
  later by the word-alignment matching step, or estimated proportionally
  from the audio duration when alignment fails (``None`` until then).

Idle standby variants are **not** part of this list: they are persistent
state rather than timed performance, so they are switched out-of-band via
the ``set_idle`` LLM tool, which sends a dedicated wire message.
"""

import re
from collections.abc import Sequence

from pydantic import BaseModel

from astrbot.api import logger

# Fixed 24-word emotion vocabulary, kept in sync with the frontend engine.
EMOTION_WORDS: tuple[str, ...] = (
    "neutral",
    "happy",
    "excited",
    "amused",
    "proud",
    "confident",
    "calm",
    "relieved",
    "affectionate",
    "shy",
    "embarrassed",
    "curious",
    "concerned",
    "confused",
    "tired",
    "sad",
    "lonely",
    "disappointed",
    "anxiety",
    "fear",
    "anger",
    "frustrated",
    "disgust",
    "surprised",
)
_EMOTIONS_CASEFOLDED = {word.casefold(): word for word in EMOTION_WORDS}

# Fixed intensity: the LLM no longer emits per-segment intensity.
DEFAULT_INTENSITY = 1

# Any bracketed token; validity against the vocabulary is checked at parse
# time so non-vocabulary brackets (e.g. leftover action descriptions) stay
# literal text instead of being swallowed as tags.
_BRACKET_RE = re.compile(r"(\[[^\[\]\n]*\])")

# --- Performance model -----------------------------------------------------


class Performance(BaseModel):
    """One segment of the tagged reply: a dialogue run with the emotion to
    express while speaking it.

    ``start`` / ``end`` are the segment's time window inside the single
    shared TTS audio (seconds), filled by the alignment matching step or,
    when alignment fails, estimated proportionally from the audio
    duration; they are ``None`` until then. The audio itself lives on the
    wire message next to the performance list, not per segment.
    """

    text: str
    emotion: str = "neutral"
    intensity: float = DEFAULT_INTENSITY
    start: float | None = None
    end: float | None = None


# --- Parser ----------------------------------------------------------------


def match_allowed_name(raw: str, allowed: Sequence[str] | None) -> str | None:
    """Resolve a field value against the allowed-name whitelist.

    Prompt-side constraints alone cannot stop the LLM from inventing names,
    so validity is enforced here at parse time. Matching is case-insensitive;
    anything that does not exactly match an allowed name is rejected so a
    fabricated value is dropped rather than silently remapped.

    Args:
        raw: The field value as emitted by the LLM.
        allowed: The allowed names, or ``None`` to accept anything.

    Returns:
        The canonical allowed name, or ``None`` when ``raw`` matches nothing.
    """
    if allowed is None:
        return raw
    lowered = {name.casefold(): name for name in allowed}
    return lowered.get(raw.casefold())


def parse_tagged_text(text: str) -> list[Performance] | None:
    """Parse the director's tag-annotated reply into performance segments.

    The expected input is the original reply text with inline ``[emotion]``
    markers inserted; each marker applies from its position up to the next
    marker, and text before the first marker defaults to ``neutral``.
    Bracketed tokens that are not vocabulary words are kept as literal
    text. When nothing performable remains, ``None`` is returned.

    Args:
        text: The raw LLM output text.

    Returns:
        The ordered list of performance segments, or ``None`` when the
        output holds no dialogue at all.
    """
    # Tolerate a wrapped code fence (``` ... ``` or ```json ... ```).
    stripped = text.strip()
    if stripped.startswith("```"):
        stripped = re.sub(r"^```[a-zA-Z]*\n?", "", stripped)
        stripped = re.sub(r"\n?```\s*$", "", stripped).strip()

    segments: list[tuple[str, str]] = []  # (emotion, text)
    current_emotion = "neutral"
    buf = ""
    for token in _BRACKET_RE.split(stripped):
        if token.startswith("[") and token.endswith("]"):
            word = token[1:-1].strip()
            emotion = _EMOTIONS_CASEFOLDED.get(word.casefold())
            if emotion is None:
                # Not a vocabulary tag (e.g. leftover action description):
                # keep the bracket verbatim in the dialogue text.
                if word:
                    logger.warning(
                        "[Performance] bracket not a known emotion tag, "
                        "kept as literal text: %s",
                        token,
                    )
                buf += token
                continue
            if buf.strip():
                segments.append((current_emotion, buf.strip()))
            buf = ""
            current_emotion = emotion
        else:
            buf += token
    if buf.strip():
        segments.append((current_emotion, buf.strip()))

    if not segments:
        logger.warning("[Performance] no performable text parsed from output")
        return None
    return [Performance(text=t, emotion=e) for e, t in segments]
